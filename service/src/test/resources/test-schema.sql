-- Schéma équivalent à db/postgres/01_schema.sql, adapté à H2 pour les tests
CREATE TABLE departement (code VARCHAR(10) PRIMARY KEY, libelle VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE employee (
  matricule VARCHAR(20) PRIMARY KEY, nom VARCHAR(100) NOT NULL, prenom VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE, telephone VARCHAR(20), date_naissance DATE NOT NULL,
  date_embauche DATE NOT NULL, departement VARCHAR(100) NOT NULL REFERENCES departement(libelle),
  poste VARCHAR(100) NOT NULL, salaire NUMERIC(12,2) NOT NULL, statut VARCHAR(10) NOT NULL,
  source VARCHAR(10) NOT NULL DEFAULT 'MYSQL', updated_at TIMESTAMP(3) NOT NULL DEFAULT now());
CREATE TABLE employee_changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, matricule VARCHAR(20) NOT NULL REFERENCES employee(matricule),
  operation VARCHAR(10) NOT NULL, changed_at TIMESTAMP(3) NOT NULL DEFAULT now(),
  processed BOOLEAN NOT NULL DEFAULT FALSE, processed_at TIMESTAMP(3));
